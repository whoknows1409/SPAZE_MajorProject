#!/usr/bin/env python3
"""
SPAZE - PAKL provisioning

Creates the secrets needed for SECURITY_MODE=pakl:
  secrets/pakl.env              MASTER_KEY (wraps FEKs at rest on the server)
  secrets/device.key            this workstation's HMAC key (agent request signing)
  secrets/tls/server.{crt,key}  self-signed TLS certificate for the server
  firmware/badge/badge_secrets.h    BADGE_ID + BADGE_KEY for the badge firmware
  firmware/anchor/anchor_secrets.h  ANCHOR_KEY (signs challenge-response timings)
and stores the badge/device/anchor keys in the database, wrapped under MASTER_KEY.

Run from the project root with the venv active:
  python scripts/provision_pakl.py --badge-mac 5c:01:3b:4b:e3:2a --wrap-existing

Re-running is safe: existing secrets are kept unless --rotate is given.
"""

import argparse
import asyncio
import os
import secrets
import socket
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
os.chdir(ROOT)  # server settings read .env from the working directory

from sqlalchemy import select  # noqa: E402

from server.db.database import async_session, init_db, close_db  # noqa: E402
from server.db.models import Badge, Device, FileKey  # noqa: E402
from server.security import pakl  # noqa: E402

SECRETS = ROOT / "secrets"
BADGE_HEADER = ROOT / "firmware" / "badge" / "badge_secrets.h"
ANCHOR_HEADER = ROOT / "firmware" / "anchor" / "anchor_secrets.h"


def _rel(path: Path) -> str:
    try:
        return str(path.relative_to(ROOT))
    except ValueError:
        return str(path)


def load_env_file(path: Path) -> dict:
    values = {}
    if path.exists():
        for line in path.read_text().splitlines():
            if "=" in line and not line.lstrip().startswith("#"):
                k, v = line.split("=", 1)
                values[k.strip()] = v.strip()
    return values


def ensure_master_key(rotate: bool) -> bytes:
    env_path = SECRETS / "pakl.env"
    values = load_env_file(env_path)
    if values.get("MASTER_KEY") and not rotate:
        print(f"  MASTER_KEY: kept ({env_path})")
        return bytes.fromhex(values["MASTER_KEY"])
    if values.get("MASTER_KEY") and rotate:
        print("  ! Not rotating MASTER_KEY: wrapped FEKs would become unreadable.")
        return bytes.fromhex(values["MASTER_KEY"])
    key = secrets.token_bytes(32)
    env_path.write_text(
        "# SPAZE PAKL server secrets - load with: set -a; source secrets/pakl.env; set +a\n"
        f"MASTER_KEY={key.hex()}\n"
    )
    env_path.chmod(0o600)
    print(f"  MASTER_KEY: generated ({env_path})")
    return key


def write_badge_header(badge_id: int, key: bytes):
    body = ", ".join(f"0x{b:02x}" for b in key)
    BADGE_HEADER.write_text(
        "// Generated by scripts/provision_pakl.py - DO NOT COMMIT\n"
        "#pragma once\n"
        f"#define BADGE_ID {badge_id}UL\n"
        f"static const uint8_t BADGE_KEY[32] = {{{body}}};\n"
    )
    BADGE_HEADER.chmod(0o600)
    print(f"  Badge header: {_rel(BADGE_HEADER)} (flash the badge after this)")


def write_anchor_header(key: bytes):
    body = ", ".join(f"0x{b:02x}" for b in key)
    ANCHOR_HEADER.write_text(
        "// Generated by scripts/provision_pakl.py - DO NOT COMMIT\n"
        "#pragma once\n"
        f"static const uint8_t ANCHOR_KEY[32] = {{{body}}};\n"
    )
    ANCHOR_HEADER.chmod(0o600)
    print(f"  Anchor header: {_rel(ANCHOR_HEADER)} (flash the anchor after this)")


def ensure_tls(hosts: list[str]):
    tls = SECRETS / "tls"
    tls.mkdir(parents=True, exist_ok=True)
    crt, key = tls / "server.crt", tls / "server.key"
    if crt.exists() and key.exists():
        print(f"  TLS cert: kept ({_rel(crt)})")
        return
    san = ",".join(
        (f"IP:{h}" if h.replace(".", "").isdigit() else f"DNS:{h}") for h in hosts
    )
    subprocess.run([
        "openssl", "req", "-x509", "-newkey", "ec", "-pkeyopt", "ec_paramgen_curve:P-256",
        "-nodes", "-days", "365", "-keyout", str(key), "-out", str(crt),
        "-subj", "/CN=spaze-server", "-addext", f"subjectAltName={san}",
    ], check=True, capture_output=True)
    key.chmod(0o600)
    print(f"  TLS cert: generated for {san}")


async def provision(args):
    SECRETS.mkdir(exist_ok=True)
    SECRETS.chmod(0o700)

    await init_db()  # also applies the additive PAKL column migrations
    master_key = ensure_master_key(args.rotate)

    async with async_session() as db:
        badge = (await db.execute(
            select(Badge).where(Badge.mac_address == args.badge_mac)
        )).scalar_one_or_none()
        if badge is None:
            sys.exit(f"Badge {args.badge_mac} is not registered (register it in the dashboard first)")

        if not badge.hmac_secret or args.rotate:
            bkey = secrets.token_bytes(32)
            args.reset_replay_state = True  # new key: forget the old anti-replay state
            print(f"  Badge #{badge.id} key: generated")
        else:
            bkey = pakl.unwrap_secret(master_key, badge.hmac_secret, f"badge|{badge.id}")
            print(f"  Badge #{badge.id} key: kept")
        badge.hmac_secret = pakl.wrap_secret(master_key, bkey, f"badge|{badge.id}")
        if args.reset_replay_state:
            badge.tok_last_counter = None
            badge.tok_offset_ref = None
            badge.tok_ref_time = None
            badge.tok_last_counter_time = None
            print(f"  Badge #{badge.id} anti-replay state: reset")
        write_badge_header(badge.id, bkey)

        device = (await db.execute(
            select(Device).where(Device.hostname == args.hostname)
        )).scalars().first()
        if device is None:
            sys.exit(f"Device '{args.hostname}' is not registered (register it in the dashboard first)")

        device_key_path = SECRETS / "device.key"
        if not device.api_secret or args.rotate or not device_key_path.exists():
            dkey = secrets.token_bytes(32)
            print(f"  Device '{device.hostname}' key: generated")
        else:
            dkey = pakl.unwrap_secret(master_key, device.api_secret, f"device|{device.id}")
            print(f"  Device '{device.hostname}' key: kept")
        device.api_secret = pakl.wrap_secret(master_key, dkey, f"device|{device.id}")
        device_key_path.write_text(dkey.hex() + "\n")
        device_key_path.chmod(0o600)

        if not device.anchor_secret or args.rotate or not ANCHOR_HEADER.exists():
            akey = secrets.token_bytes(32)
            print(f"  Anchor key for '{device.hostname}': generated")
        else:
            akey = pakl.unwrap_secret(master_key, device.anchor_secret, f"anchor|{device.id}")
            print(f"  Anchor key for '{device.hostname}': kept")
        device.anchor_secret = pakl.wrap_secret(master_key, akey, f"anchor|{device.id}")
        write_anchor_header(akey)
        print("  Badge, device and anchor keys stored wrapped under MASTER_KEY")

        if args.wrap_existing:
            wrapped = 0
            for fk in (await db.execute(select(FileKey))).scalars().all():
                if not pakl.is_wrapped(fk.encrypted_fek):
                    fk.encrypted_fek = pakl.wrap_fek(master_key, fk.encrypted_fek, fk.device_id, fk.file_path)
                    wrapped += 1
            print(f"  Wrapped {wrapped} stored FEK(s) with MASTER_KEY")

        await db.commit()

    # Drop cached key blobs so the server re-reads (wrapped) values
    try:
        from server.cache import get_redis, close_redis
        r = await get_redis()
        n = 0
        async for k in r.scan_iter("spaze:keys:*"):
            await r.delete(k)
            n += 1
        await close_redis()
        print(f"  Cleared {n} cached key entr{'y' if n == 1 else 'ies'} in Redis")
    except Exception as e:
        print(f"  ! Could not clear Redis key cache: {e}")

    ensure_tls(args.tls_hosts)
    await close_db()


def main():
    parser = argparse.ArgumentParser(description="Provision SPAZE PAKL secrets")
    parser.add_argument("--badge-mac", required=True, help="Registered badge MAC (as stored in the DB)")
    parser.add_argument("--hostname", default=socket.gethostname(), help="Registered device hostname")
    parser.add_argument("--tls-hosts", nargs="+", default=["localhost", "127.0.0.1"],
                        help="Names/IPs the server certificate is valid for")
    parser.add_argument("--wrap-existing", action="store_true", help="Wrap legacy unwrapped FEKs")
    parser.add_argument("--rotate", action="store_true", help="Regenerate badge and device keys")
    parser.add_argument("--reset-replay-state", action="store_true",
                        help="Forget the badge's last counter (needed after erasing the badge flash)")
    args = parser.parse_args()

    print("SPAZE PAKL provisioning")
    asyncio.run(provision(args))
    print("Done.")


if __name__ == "__main__":
    main()
