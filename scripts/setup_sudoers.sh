#!/bin/bash
# ============================================================
# SPAZE — One-time Setup Script
# Creates sudoers rules for passwordless tmpfs mount/umount
# and prepares the mount point directory.
#
# Run once: sudo bash scripts/setup_sudoers.sh
# ============================================================

set -e

ACTUAL_USER="${SUDO_USER:-$USER}"
MOUNT_POINT="/home/$ACTUAL_USER/spaze"
SUDOERS_FILE="/etc/sudoers.d/spaze"

echo "============================================"
echo "  SPAZE Setup Script"
echo "============================================"
echo ""

# Must be run as root
if [ "$EUID" -ne 0 ]; then
    echo "❌ This script must be run with sudo:"
    echo "   sudo bash scripts/setup_sudoers.sh"
    exit 1
fi

echo "[1/4] Creating mount point: $MOUNT_POINT"
mkdir -p "$MOUNT_POINT"
chown "$ACTUAL_USER:$ACTUAL_USER" "$MOUNT_POINT"
chmod 700 "$MOUNT_POINT"
echo "  ✅ Created with owner=$ACTUAL_USER, mode=700"

echo ""
echo "[2/4] Setting up passwordless sudo for mount/umount/swap..."

# Create sudoers rule — ONLY allows mount/umount of spaze tmpfs + swap control
cat > "$SUDOERS_FILE" << EOF
# SPAZE — Allow passwordless tmpfs mount/umount and swap control
# This file was auto-generated by scripts/setup_sudoers.sh
$ACTUAL_USER ALL=(root) NOPASSWD: /usr/bin/mount -t tmpfs -o size=*\,noexec\,nosuid\,nodev\,mode=700\,uid=* spaze-tmpfs /home/$ACTUAL_USER/spaze
$ACTUAL_USER ALL=(root) NOPASSWD: /usr/bin/umount /home/$ACTUAL_USER/spaze
$ACTUAL_USER ALL=(root) NOPASSWD: /usr/bin/umount -l /home/$ACTUAL_USER/spaze
$ACTUAL_USER ALL=(root) NOPASSWD: /sbin/swapoff -a
$ACTUAL_USER ALL=(root) NOPASSWD: /sbin/swapon -a
EOF

chmod 440 "$SUDOERS_FILE"
echo "  ✅ Sudoers rule written to $SUDOERS_FILE"

# Validate sudoers syntax
if visudo -cf "$SUDOERS_FILE" > /dev/null 2>&1; then
    echo "  ✅ Sudoers syntax valid"
else
    echo "  ❌ Sudoers syntax error! Removing file."
    rm -f "$SUDOERS_FILE"
    exit 1
fi

echo ""
echo "[3/4] Checking dependencies..."
for cmd in lsof swapon; do
    if command -v $cmd &> /dev/null; then
        echo "  ✅ $cmd found"
    else
        echo "  ⚠️  $cmd not found (install with: sudo apt install $cmd)"
    fi
done

echo ""
echo "[4/4] Testing mount/umount..."
if sudo -n mount -t tmpfs -o "size=1m,noexec,nosuid,nodev,mode=700,uid=$(id -u $ACTUAL_USER)" spaze-tmpfs "$MOUNT_POINT" 2>/dev/null; then
    echo "  ✅ Mount test passed"
    sudo -n umount "$MOUNT_POINT" 2>/dev/null
    echo "  ✅ Umount test passed"
else
    echo "  ⚠️  Mount test failed — you may need to reboot for sudoers to take effect"
fi

echo ""
echo "============================================"
echo "  ✅ SPAZE Setup Complete!"
echo "============================================"
echo ""
echo "Mount point:  $MOUNT_POINT"
echo "Sudoers rule: $SUDOERS_FILE"
echo ""
echo "You can now run the agent without entering your password:"
echo "  cd ~/Documents/MajorProject"
echo "  source venv/bin/activate"
echo "  python -m agent.main --port /dev/ttyACM0"
echo ""
